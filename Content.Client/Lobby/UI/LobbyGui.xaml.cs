    [GenerateTypedNameReferences]
    public sealed partial class LobbyGui : UIScreen
    {
        // The character editor's own minimum width is roughly 1330 px; keep a little slack so the
        // mark list, tabs and preview are not squished.
        private const float CharacterSetupMinWidth = 1400f;
        private const int ChatGap = 8;
        private static readonly Color TransparentMenuColor = Color.FromHex("#252725C7");

        // Menu blur: the card is at most 680x640, so a chunky CPU downscale is plenty. The blur runs
        // when the background or the panel size changes, never per frame.
        private const int BackdropDownscale = 8;
        private const int BackdropSourceMaxDimension = 256;
        private const int BackdropBlurRadius = 2;
        private const float BackdropChamfer = 10f;

        [Dependency] private IClientConsoleHost _consoleHost = default!;
        [Dependency] private IResourceManager _resourceManager = default!;

        private readonly Dictionary<string, BlurSource?> _blurSources = new();

        private LobbyGuiState _state = LobbyGuiState.Default;
        private bool _chatHasSpace = true;
        private int _chatWidth = 650;
        private bool _menuTransparent = true;
        private bool _menuBlur = true;

        private string? _menuBackground;
        private string? _menuBackgroundNext;
        private string? _builtMenuBackground;
        private string? _builtMenuBackgroundNext;
        private Vector2i _builtMenuPanelSize;
        private Vector2i _builtMenuBackgroundSize;
        private float _builtMenuUIScale;

        private readonly record struct BlurSource(Image<Rgba32> Image, Vector2i Size);

        public LobbyGui()
        {
            RobustXamlLoader.Load(this);
            IoCManager.InjectDependencies(this);
            SetAnchorPreset(MainContainer, LayoutPreset.Wide);
            SetAnchorPreset(Background, LayoutPreset.Wide);
            SetAnchorPreset(BackgroundFade, LayoutPreset.Wide);

            LayoutContainer.SetAnchorPreset(MainMenuPanel, LayoutContainer.LayoutPreset.Center);
            LayoutContainer.SetGrowHorizontal(MainMenuPanel, LayoutContainer.GrowDirection.Both);
            LayoutContainer.SetGrowVertical(MainMenuPanel, LayoutContainer.GrowDirection.Both);
            LayoutContainer.SetAnchorPreset(CharacterSetupPanel, LayoutContainer.LayoutPreset.Wide);
            LayoutContainer.SetAnchorPreset(ChatPanel, LayoutContainer.LayoutPreset.RightWide);
            LayoutContainer.SetAnchorPreset(ChatCollapsedPanel, LayoutContainer.LayoutPreset.BottomRight);
            LayoutContainer.SetGrowHorizontal(ChatPanel, LayoutContainer.GrowDirection.Begin);
            LayoutContainer.SetGrowVertical(ChatPanel, LayoutContainer.GrowDirection.Begin);
            LayoutContainer.SetGrowHorizontal(ChatCollapsedPanel, LayoutContainer.GrowDirection.Begin);
            LayoutContainer.SetGrowVertical(ChatCollapsedPanel, LayoutContainer.GrowDirection.Begin);
            LayoutContainer.SetMarginTop(ChatPanel, 8);
            LayoutContainer.SetMarginBottom(ChatPanel, -8);
            LayoutContainer.SetMarginRight(ChatPanel, -8);
            LayoutContainer.SetMarginRight(ChatCollapsedPanel, -8);
            LayoutContainer.SetMarginBottom(ChatCollapsedPanel, -8);

            ChatCollapsedPanel.MinSize = new Vector2(150, 56);
            SetChatOpen(false);

            LobbySong.SetMarkup(Loc.GetString("lobby-state-song-no-song-text"));

            LeaveButton.OnPressed += _ => _consoleHost.ExecuteCommand("disconnect");
            OptionsButton.OnPressed += _ => UserInterfaceManager.GetUIController<OptionsUIController>().ToggleWindow();

            ChatCollapseButton.OnPressed += _ => SetChatOpen(false);
            ChatExpandButton.OnPressed += _ => SetChatOpen(true);

            MainMenuPanel.OnResized += OnMenuLayoutChanged;
            Background.OnResized += OnMenuLayoutChanged;
        }

        protected override void UIScaleChanged()
        {
            base.UIScaleChanged();
            RebuildMenuBackdrop(force: true);
        }

        private void OnMenuLayoutChanged()
        {
            RebuildMenuBackdrop();
        }

        public void SetChatOpen(bool open)
        {
            if (_state == LobbyGuiState.CharacterSetup)
            {
                if (!_chatHasSpace)
                {
                    ChatPanel.Visible = false;
                    ChatCollapsedPanel.Visible = false;
                    ChatCollapseButton.Visible = false;
                    LayoutContainer.SetMarginRight(CharacterSetupPanel, 0);
                    return;
                }

                // In character setup the chat is a fixed column: it cannot be collapsed and the
                // editor cannot reclaim its space.
                open = true;
                ChatCollapseButton.Visible = false;
            }
            else
            {
                ChatCollapseButton.Visible = true;
            }

            ChatPanel.Visible = open;
            ChatCollapsedPanel.Visible = !open;

            if (_state == LobbyGuiState.CharacterSetup)
            {
                // Wide anchors add the right margin to the parent width, so a negative margin
                // shrinks the editor and reserves a column for the chat.
                LayoutContainer.SetMarginRight(CharacterSetupPanel,
                    open ? -(_chatWidth + ChatGap * 2) : 0);
            }
        }

        public void SetChatWidth(int width)
        {
            _chatWidth = Math.Max(465, width);
            // LayoutContainer only uses the measured size for anchored children, so MinWidth is
            // what actually reserves the chat column.
            ChatPanel.MinWidth = _chatWidth;
            ChatPanel.SetWidth = _chatWidth;

            if (_state == LobbyGuiState.CharacterSetup && ChatPanel.Visible)
            {
                LayoutContainer.SetMarginRight(CharacterSetupPanel,
                    -(_chatWidth + ChatGap * 2));
            }
        }

        /// <summary>
        /// Palmtree: alpha-only transparency for the main menu card. The blur only applies while
        /// transparency is enabled, so turning transparency off also removes the frosted backdrop.
        /// </summary>
        public void SetMenuTransparent(bool enabled)
        {
            _menuTransparent = enabled;
            MainMenuPanel.ModulateSelfOverride = enabled ? TransparentMenuColor : null;
            UpdateMenuBackdropState(force: true);
        }

        /// <summary>
        /// Palmtree: enables the pre-blurred copy of the lobby background behind the menu card.
        /// No shader and no screen copy. Only takes effect while the menu is transparent.
        /// </summary>
        public void SetMenuBlur(bool enabled)
        {
            _menuBlur = enabled;
            UpdateMenuBackdropState(force: true);
        }

        private void UpdateMenuBackdropState(bool force)
        {
            MainMenuPanel.BackdropEnabled = _menuTransparent && _menuBlur;
            RebuildMenuBackdrop(force);
        }

        /// <summary>
        /// Palmtree: tells the menu which lobby background is on screen so it can build the blurred
        /// card backdrop. <paramref name="next"/> is only set during a crossfade.
        /// </summary>
        public void SetMenuBackground(string? background, string? next = null)
        {
            if (_menuBackground == background && _menuBackgroundNext == next)
                return;

            _menuBackground = background;
            _menuBackgroundNext = next;
            MainMenuPanel.BackdropFade = 0f;
            RebuildMenuBackdrop(force: true);
        }

        /// <summary>
        /// Palmtree: crossfade progress for the menu backdrop. Safe to call every frame.
        /// </summary>
        public void SetMenuBackgroundFade(float fade)
        {
            MainMenuPanel.BackdropFade = Math.Clamp(fade, 0f, 1f);
        }

        /// <summary>
        /// Palmtree: releases the menu backdrop textures and decoded background images.
        /// </summary>
        public void ClearMenuBackdrop()
        {
            ClearBackdropTextures();

            foreach (var source in _blurSources.Values)
                source?.Image.Dispose();

            _blurSources.Clear();
            _menuBackground = null;
            _menuBackgroundNext = null;
            _builtMenuBackground = null;
            _builtMenuBackgroundNext = null;
            _builtMenuPanelSize = default;
            _builtMenuBackgroundSize = default;
            _builtMenuUIScale = 0f;
        }

        private void RebuildMenuBackdrop(bool force = false)
        {
            var panelSize = MainMenuPanel.PixelSize;
            var backgroundSize = Background.PixelSize;
            var uiScale = MainMenuPanel.UIScale;

            if (!force
                && panelSize == _builtMenuPanelSize
                && backgroundSize == _builtMenuBackgroundSize
                && MathF.Abs(uiScale - _builtMenuUIScale) < 0.001f
                && _menuBackground == _builtMenuBackground
                && _menuBackgroundNext == _builtMenuBackgroundNext)
            {
                return;
            }

            _builtMenuPanelSize = panelSize;
            _builtMenuBackgroundSize = backgroundSize;
            _builtMenuUIScale = uiScale;
            _builtMenuBackground = _menuBackground;
            _builtMenuBackgroundNext = _menuBackgroundNext;

            if (!MainMenuPanel.BackdropEnabled
                || !MainMenuPanel.Visible
                || panelSize.X <= 0
                || panelSize.Y <= 0
                || backgroundSize.X <= 0
                || backgroundSize.Y <= 0
                || _menuBackground == null)
            {
                ClearBackdropTextures();
                return;
            }

            var current = BuildMenuBackdrop(_menuBackground, panelSize, backgroundSize, uiScale);
            var next = _menuBackgroundNext != null
                ? BuildMenuBackdrop(_menuBackgroundNext, panelSize, backgroundSize, uiScale)
                : null;

            SetBackdropTextures(current, next);
        }

        private void SetBackdropTextures(Texture? current, Texture? next)
        {
            if (!ReferenceEquals(MainMenuPanel.Backdrop, current))
            {
                (MainMenuPanel.Backdrop as IDisposable)?.Dispose();
                MainMenuPanel.Backdrop = current;
            }

            if (!ReferenceEquals(MainMenuPanel.BackdropNext, next))
            {
                (MainMenuPanel.BackdropNext as IDisposable)?.Dispose();
                MainMenuPanel.BackdropNext = next;
            }
        }

        private void ClearBackdropTextures()
        {
            (MainMenuPanel.Backdrop as IDisposable)?.Dispose();
            (MainMenuPanel.BackdropNext as IDisposable)?.Dispose();
            MainMenuPanel.Backdrop = null;
            MainMenuPanel.BackdropNext = null;
            MainMenuPanel.BackdropFade = 0f;
        }

        private Texture? BuildMenuBackdrop(string path, Vector2i panelSize, Vector2i backgroundSize, float uiScale)
        {
            if (!TryGetBlurSource(path, out var source))
                return null;

            var fullCrop = GetBackgroundSourceRect(source.Size, panelSize, backgroundSize);
            if (fullCrop.Width <= 0 || fullCrop.Height <= 0)
                return null;

            // GetBackgroundSourceRect works in full-image pixels; the cached copy is smaller.
            var smallWidth = source.Image.Width;
            var smallHeight = source.Image.Height;
            var cropX = Math.Clamp(
                (int)MathF.Floor(fullCrop.X * smallWidth / (float)source.Size.X),
                0,
                smallWidth - 1);
            var cropY = Math.Clamp(
                (int)MathF.Floor(fullCrop.Y * smallHeight / (float)source.Size.Y),
                0,
                smallHeight - 1);
            var crop = new LobbyMenuBackdropBuilder.CropRect(
                cropX,
                cropY,
                Math.Clamp(
                    (int)MathF.Ceiling(fullCrop.Width * smallWidth / (float)source.Size.X),
                    1,
                    smallWidth - cropX),
                Math.Clamp(
                    (int)MathF.Ceiling(fullCrop.Height * smallHeight / (float)source.Size.Y),
                    1,
                    smallHeight - cropY));

            using var image = LobbyMenuBackdropBuilder.Build(
                source.Image,
                crop,
                panelSize,
                BackdropDownscale,
                BackdropBlurRadius,
                BackdropChamfer * uiScale);

            var loadParameters = TextureLoadParameters.Default;
            loadParameters.SampleParameters = new TextureSampleParameters
            {
                Filter = true,
                WrapMode = TextureWrapMode.None,
            };

            return Texture.LoadFromImage(image, $"lobby-menu-backdrop:{path}", loadParameters);
        }

        private LobbyMenuBackdropBuilder.CropRect GetBackgroundSourceRect(
            Vector2i imageSize,
            Vector2i panelSize,
            Vector2i backgroundSize)
        {
            var scale = MathF.Max(
                backgroundSize.X / (float)imageSize.X,
                backgroundSize.Y / (float)imageSize.Y);

            if (scale <= 0f)
                return default;

            var drawSize = new Vector2(imageSize.X * scale, imageSize.Y * scale);
            var drawOffset = (new Vector2(backgroundSize.X, backgroundSize.Y) - drawSize) / 2f;

            var panel = MainMenuPanel.GlobalPixelRect;
            var background = Background.GlobalPixelRect;
            var local = new Vector2(panel.Left - background.Left, panel.Top - background.Top);

            var x = (local.X - drawOffset.X) / scale;
            var y = (local.Y - drawOffset.Y) / scale;
            var width = panelSize.X / scale;
            var height = panelSize.Y / scale;

            x = Math.Clamp(x, 0f, imageSize.X);
            y = Math.Clamp(y, 0f, imageSize.Y);
            width = Math.Clamp(width, 0f, imageSize.X - x);
            height = Math.Clamp(height, 0f, imageSize.Y - y);

            var left = (int)MathF.Floor(x);
            var top = (int)MathF.Floor(y);
            var right = Math.Min((int)MathF.Ceiling(x + width), imageSize.X);
            var bottom = Math.Min((int)MathF.Ceiling(y + height), imageSize.Y);

            return new LobbyMenuBackdropBuilder.CropRect(left, top, right - left, bottom - top);
        }

        private bool TryGetBlurSource(string path, out BlurSource source)
        {
            if (_blurSources.TryGetValue(path, out var cached))
            {
                if (cached != null)
                {
                    source = cached.Value;
                    return true;
                }

                source = default;
                return false;
            }

            try
            {
                using var stream = _resourceManager.ContentFileRead(path);
                using var full = Image.Load<Rgba32>(stream);

                var size = new Vector2i(full.Width, full.Height);
                var scale = MathF.Min(1f, BackdropSourceMaxDimension / (float)Math.Max(full.Width, full.Height));
                var width = Math.Max(1, (int)MathF.Round(full.Width * scale));
                var height = Math.Max(1, (int)MathF.Round(full.Height * scale));

                // Keep only a small copy around. The per-card blur is built from this cache, so each
                // background file is decoded once per session.
                var pixels = LobbyMenuBackdropBuilder.Downscale(
                    full,
                    new LobbyMenuBackdropBuilder.CropRect(0, 0, full.Width, full.Height),
                    width,
                    height);
                var image = new Image<Rgba32>(width, height);
                var span = image.GetPixelSpan();
                for (var i = 0; i < pixels.Length; i++)
                    span[i] = pixels[i];

                source = new BlurSource(image, size);
                _blurSources[path] = source;
                return true;
            }
            catch (Exception e)
            {
                Logger.GetSawmill("lobby.menu").Error(
                    $"Failed to load lobby background '{path}' for the menu backdrop: {e}");
                _blurSources[path] = null;
                source = default;
                return false;
            }
        }

        public void SetReadyState(bool ready, bool visible = true)
        {
            ReadyStatusIcon.Visible = visible;
            if (!visible)
                return;

            ReadyStatusIcon.TexturePath = ready
                ? "/Textures/Interface/Nano/checkbox_checked.svg.96dpi.png"
                : "/Textures/Interface/Nano/cross.svg.png";
            ReadyStatusIcon.ModulateSelfOverride = ready ? Color.LimeGreen : Color.IndianRed;
        }

        public void SwitchState(LobbyGuiState state)
        {
            _state = state;
            MainMenuPanel.Visible = false;
            CharacterSetupPanel.Visible = false;

            switch (state)
            {
                case LobbyGuiState.Default:
                    MainMenuPanel.Visible = true;
                    LayoutContainer.SetMarginRight(CharacterSetupPanel, 0);
                    _chatHasSpace = true;
                    SetChatOpen(false);
                    RebuildMenuBackdrop(force: true);
                    break;
                case LobbyGuiState.CharacterSetup:
                    CharacterSetupPanel.Visible = true;

                    // Old lobby behaviour: split the editor with chat only when the editor still has
                    // enough room. On small screens there is no chat button or panel in this state.
                    var width = MainContainer.Size.X > 0
                        ? MainContainer.Size.X
                        : UserInterfaceManager.RootControl.Size.X;
                    _chatHasSpace = width - _chatWidth - ChatGap * 2 >= CharacterSetupMinWidth;

                    if (_chatHasSpace)
                        SetChatOpen(true);
                    else
                        SetChatOpen(false);

                    // Only reload the shared editor when this is the screen currently displayed.
                    // Standalone instances (tests, previews) must not touch the live editor.
                    if (UserInterfaceManager.ActiveScreen == this)
                        UserInterfaceManager.GetUIController<LobbyUIController>().ReloadCharacterSetup();
                    break;
            }

        }

        public enum LobbyGuiState : byte
        {
            /// <summary>
            ///  The default state, i.e., what's seen on launch.
            /// </summary>
            Default,
            /// <summary>
            ///  The character setup state.
            /// </summary>
            CharacterSetup
        }
    }
