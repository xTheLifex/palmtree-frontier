using System.Linq;
using System.Numerics;
using Content.Client._PS.UserInterface;
using Content.Client._PS.UserInterface.Controls;
using Content.Shared._PS.Interactions;
using Content.Shared._PS.Organs;
using Content.Shared.Humanoid.Markings;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client._PS.Organs.UI;

/// <summary>
/// Palmtree: the detail editor for one genital organ type. The panel is intentionally independent
/// from the profile: it receives a <see cref="GenitalOrganData"/> and emits <see cref="Changed"/>
/// when the user edits it. Only the selected organ panel is visible at a time.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class GenitalOrganPanel : BoxContainer
{
    private static readonly GenitalVisibility[] VisibilityOrder =
    {
        GenitalVisibility.AlwaysHidden,
        GenitalVisibility.HiddenByUnderwear,
        GenitalVisibility.HiddenByJumpsuit,
        GenitalVisibility.VisibleUnderClothes,
        GenitalVisibility.NeverHidden,
    };

    public event Action? Changed;

    public GenitalType Type { get; }

    private readonly List<GenitalOrganPrototype> _catalogs;
    private readonly IPrototypeManager _prototypes;

    private ColorSelectorWithClipboard _primaryColor = default!;
    private ColorSelectorWithClipboard _detailColor = default!;
    private SliderSpinBox _scaleX = default!;
    private SliderSpinBox _scaleY = default!;
    private SliderSpinBox _offsetX = default!;
    private SliderSpinBox _offsetY = default!;
    private SliderSpinBox _glow = default!;
    private SliderSpinBox _detailGlow = default!;

    private Color _skinColor = Color.White;
    private bool _colorsCustomized;
    private bool _detailColorVisible;
    private bool _separateScale;
    private bool _suppress;

    public bool Enabled => EnabledCheck.Pressed;

    public string Summary => SummaryLabel.Text ?? string.Empty;

    public GenitalOrganPanel(
        GenitalType type,
        List<GenitalOrganPrototype> catalogs,
        IPrototypeManager prototypes)
    {
        Type = type;
        _catalogs = catalogs;
        _prototypes = prototypes;

        RobustXamlLoader.Load(this);

        TitleLabel.Text = Loc.GetString(TypeLocaleKey(type));
        BuildControls();
        WireEvents();
        UpdateVisibilityHelp();
        UpdateSkinToneVisibility();
        UpdateDetailVisibility();
        UpdateScaleControls();
        UpdateSummary();
        UpdateButtons();
    }

    /// <summary>
    /// Applies profile data to the controls without raising <see cref="Changed"/>. A null
    /// <paramref name="data"/> means the organ is disabled, but its controls stay browsable so a
    /// player can pre-configure it before enabling it.
    /// </summary>
    public void SetData(GenitalOrganData? data, Color skinColor)
    {
        _suppress = true;
        _skinColor = skinColor;

        EnabledCheck.Pressed = data != null;

        var typeIndex = 0;
        if (data != null)
        {
            var found = _catalogs.FindIndex(c => c.ID == data.Prototype);
            if (found >= 0)
                typeIndex = found;
        }

        TypeButton.SelectId(typeIndex);
        RebuildSizes(data?.Size ?? 1);
        VisibilityButton.SelectId((int) (data?.Visibility ?? GenitalVisibility.HiddenByUnderwear));

        _colorsCustomized = data != null && (data.Color != null || data.DetailColor != null);
        UseSkinCheck.Pressed = !_colorsCustomized;
        _primaryColor.Color = data?.Color ?? skinColor;
        _detailColor.Color = data?.DetailColor ?? data?.Color ?? skinColor;

        var scaleX = data?.Scale ?? 1f;
        var scaleY = data is { ScaleY: > 0f } ? data.ScaleY : scaleX;
        _separateScale = data != null && data.ScaleY > 0f && Math.Abs(data.ScaleY - data.Scale) >= 0.0001f;
        _scaleX.SetValueWithoutEvent(ToPercent(scaleX));
        _scaleY.SetValueWithoutEvent(ToPercent(scaleY));
        _offsetX.SetValueWithoutEvent(ToPercent(data?.Offset.X ?? 0f));
        _offsetY.SetValueWithoutEvent(ToPercent(data?.Offset.Y ?? 0f));
        _glow.SetValueWithoutEvent(ToPercent(data?.Glow ?? 0f));
        _detailGlow.SetValueWithoutEvent(ToPercent(data?.DetailGlow ?? 0f));
        SkinToneCheck.Pressed = data?.SkinTone ?? false;

        _suppress = false;

        UpdateColorVisibility();
        UpdateScaleControls();
        UpdateSkinToneVisibility();
        UpdateDetailVisibility();
        UpdateVisibilityHelp();
        UpdateSummary();
        UpdateButtons();
    }

    /// <summary>Builds the current organ data, or null when the organ is disabled.</summary>
    public GenitalOrganData? BuildData()
    {
        if (!EnabledCheck.Pressed || _catalogs.Count == 0)
            return null;

        var catalog = GetSelectedCatalog();
        if (catalog == null || catalog.Sizes.Count == 0)
            return null;

        var sizeIndex = Math.Clamp(SizeButton.SelectedId, 0, catalog.Sizes.Count - 1);
        var scaleX = Math.Clamp(_scaleX.Value / 100f, GenitalOrganSettings.MinScale, GenitalOrganSettings.MaxScale);
        var scaleY = _separateScale
            ? Math.Clamp(_scaleY.Value / 100f, GenitalOrganSettings.MinScale, GenitalOrganSettings.MaxScale)
            : 0f;

        if (Math.Abs(scaleY - scaleX) < 0.0001f)
            scaleY = 0f;

        return new GenitalOrganData
        {
            Prototype = catalog.ID,
            Size = sizeIndex + 1,
            Visibility = (GenitalVisibility) VisibilityButton.SelectedId,
            Color = _colorsCustomized ? _primaryColor.Color : null,
            DetailColor = _colorsCustomized ? _detailColor.Color : null,
            Offset = new Vector2(_offsetX.Value / 100f, _offsetY.Value / 100f),
            Scale = scaleX,
            ScaleY = scaleY,
            Glow = Math.Clamp(_glow.Value / 100f, 0f, 1f),
            DetailGlow = Math.Clamp(_detailGlow.Value / 100f, 0f, 1f),
            SkinTone = SkinToneCheck.Pressed,
        };
    }

    private void BuildControls()
    {
        for (var i = 0; i < _catalogs.Count; i++)
        {
            TypeButton.AddItem(Loc.GetString(_catalogs[i].Name), i);
        }

        if (_catalogs.Count > 0)
            TypeButton.SelectId(0);

        RebuildSizes(1);

        foreach (var visibility in VisibilityOrder)
        {
            VisibilityButton.AddItem(Loc.GetString(VisibilityLocaleKey(visibility)), (int) visibility);
        }

        VisibilityButton.SelectId((int) GenitalVisibility.HiddenByUnderwear);

        _primaryColor = new ColorSelectorWithClipboard
        {
            SelectorType = ColorSelectorSliders.ColorSelectorType.Hsv,
            IsAlphaVisible = true,
        };
        PrimaryColorContainer.AddChild(_primaryColor);
        _primaryColor.OnColorChanged += _ => OnColorEdited();

        _detailColor = new ColorSelectorWithClipboard
        {
            SelectorType = ColorSelectorSliders.ColorSelectorType.Hsv,
            IsAlphaVisible = true,
        };
        DetailColorContainer.AddChild(_detailColor);
        _detailColor.OnColorChanged += _ => OnColorEdited();

        _glow = new SliderSpinBox(0, 100);
        GlowContainer.AddChild(_glow);

        _detailGlow = new SliderSpinBox(0, 100);
        var detailGlowRow = new BoxContainer
        {
            Orientation = LayoutOrientation.Horizontal,
            HorizontalExpand = true,
        };
        detailGlowRow.AddChild(new Label
        {
            Text = Loc.GetString("genital-editor-detail-glow"),
            MinWidth = 80,
            VerticalAlignment = VAlignment.Center,
        });
        detailGlowRow.AddChild(_detailGlow);
        DetailColorContainer.AddChild(detailGlowRow);

        _scaleX = new SliderSpinBox(25, 300);
        ScaleContainer.AddChild(_scaleX);

        _scaleY = new SliderSpinBox(25, 300);
        ScaleYContainer.AddChild(_scaleY);

        _offsetX = new SliderSpinBox(-100, 100);
        OffsetXContainer.AddChild(_offsetX);

        _offsetY = new SliderSpinBox(-100, 100);
        OffsetYContainer.AddChild(_offsetY);

        _scaleX.SetValueWithoutEvent(100);
        _scaleY.SetValueWithoutEvent(100);
        _offsetX.SetValueWithoutEvent(0);
        _offsetY.SetValueWithoutEvent(0);
    }

    private void WireEvents()
    {
        EnabledCheck.OnToggled += _ =>
        {
            if (_suppress)
                return;

            UpdateButtons();
            Changed?.Invoke();
        };

        TypeButton.OnItemSelected += args =>
        {
            if (_suppress)
                return;

            TypeButton.SelectId(args.Id);
            RebuildSizes();
            UpdateSkinToneVisibility();
            UpdateDetailVisibility();
            UpdateSummary();
            Changed?.Invoke();
        };

        SizeButton.OnItemSelected += args =>
        {
            if (_suppress)
                return;

            SizeButton.SelectId(args.Id);
            UpdateDetailVisibility();
            UpdateSummary();
            Changed?.Invoke();
        };

        VisibilityButton.OnItemSelected += args =>
        {
            if (_suppress)
                return;

            VisibilityButton.SelectId(args.Id);
            UpdateVisibilityHelp();
            UpdateSummary();
            Changed?.Invoke();
        };

        UseSkinCheck.OnToggled += _ =>
        {
            if (_suppress)
                return;

            _colorsCustomized = !UseSkinCheck.Pressed;
            if (UseSkinCheck.Pressed)
            {
                _primaryColor.Color = _skinColor;
                _detailColor.Color = _skinColor;
            }

            UpdateColorVisibility();
            Changed?.Invoke();
        };

        _glow.ValueChanged += _ => OnSliderEdited();
        _detailGlow.ValueChanged += _ => OnSliderEdited();
        _scaleX.ValueChanged += _ => OnSliderEdited();
        _scaleY.ValueChanged += _ => OnSliderEdited();
        _offsetX.ValueChanged += _ => OnSliderEdited();
        _offsetY.ValueChanged += _ => OnSliderEdited();

        ScaleLockButton.OnPressed += _ =>
        {
            if (_suppress)
                return;

            _separateScale = !_separateScale;
            _scaleY.SetValueWithoutEvent(_scaleX.Value);

            // Unlocking only changes the widget layout; locking changes the saved data to uniform X.
            if (!_separateScale)
                Changed?.Invoke();

            UpdateScaleControls();
        };

        SkinToneCheck.OnToggled += _ =>
        {
            if (_suppress)
                return;

            Changed?.Invoke();
        };

        ResetButton.OnPressed += _ => ResetOrgan();
        RemoveButton.OnPressed += _ =>
        {
            if (!EnabledCheck.Pressed)
                return;

            EnabledCheck.Pressed = false;
        };
    }

    private void OnColorEdited()
    {
        if (_suppress)
            return;

        _colorsCustomized = true;
        Changed?.Invoke();
    }

    private void OnSliderEdited()
    {
        if (_suppress)
            return;

        Changed?.Invoke();
    }

    private void ResetOrgan()
    {
        _suppress = true;

        TypeButton.SelectId(0);
        RebuildSizes(1);
        VisibilityButton.SelectId((int) GenitalVisibility.HiddenByUnderwear);
        UseSkinCheck.Pressed = true;
        _colorsCustomized = false;
        _primaryColor.Color = _skinColor;
        _detailColor.Color = _skinColor;
        _scaleX.SetValueWithoutEvent(100);
        _scaleY.SetValueWithoutEvent(100);
        _separateScale = false;
        _offsetX.SetValueWithoutEvent(0);
        _offsetY.SetValueWithoutEvent(0);
        _glow.SetValueWithoutEvent(0);
        _detailGlow.SetValueWithoutEvent(0);
        SkinToneCheck.Pressed = false;

        _suppress = false;

        UpdateColorVisibility();
        UpdateScaleControls();
        UpdateSkinToneVisibility();
        UpdateDetailVisibility();
        UpdateVisibilityHelp();
        UpdateSummary();
        UpdateButtons();
        Changed?.Invoke();
    }

    private void RebuildSizes(int? size = null)
    {
        var catalog = GetSelectedCatalog();
        if (catalog == null)
            return;

        var wantedSize = size ?? Math.Max(1, SizeButton.SelectedId + 1);

        SizeButton.Clear();
        for (var i = 0; i < catalog.Sizes.Count; i++)
        {
            SizeButton.AddItem(Loc.GetString(catalog.Sizes[i].Name), i);
        }

        if (catalog.Sizes.Count == 0)
            return;

        SizeButton.SelectId(Math.Clamp(wantedSize - 1, 0, catalog.Sizes.Count - 1));
    }

    private void UpdateColorVisibility()
    {
        var showColors = !UseSkinCheck.Pressed;

        PrimaryColorLabel.Visible = showColors;
        PrimaryColorContainer.Visible = showColors;
        DetailColorLabel.Visible = showColors && _detailColorVisible;
        DetailColorContainer.Visible = showColors && _detailColorVisible;
    }

    private void UpdateScaleControls()
    {
        ScaleYLabel.Visible = _separateScale;
        ScaleYContainer.Visible = _separateScale;
        ScaleLabel.Text = Loc.GetString(_separateScale
            ? "genital-editor-scale-x"
            : "genital-editor-scale");
        ScaleLockButton.TexturePath = _separateScale
            ? "/Textures/Interface/VerbIcons/unlock.svg.192dpi.png"
            : "/Textures/Interface/VerbIcons/lock.svg.192dpi.png";
        ScaleLockButton.ToolTip = Loc.GetString(_separateScale
            ? "genital-editor-scale-lock-tooltip"
            : "genital-editor-scale-unlock-tooltip");
    }

    private void UpdateDetailVisibility()
    {
        _detailColorVisible = false;

        var catalog = GetSelectedCatalog();
        if (catalog != null && catalog.Sizes.Count > 0)
        {
            var sizeIndex = Math.Clamp(SizeButton.SelectedId, 0, catalog.Sizes.Count - 1);
            var flaccid = catalog.Sizes[sizeIndex].Flaccid;
            if (flaccid is { } flaccidId &&
                _prototypes.TryIndex<MarkingPrototype>(flaccidId, out var marking))
            {
                _detailColorVisible = GenitalOrganSystem.CountColorGroups(marking) > 1;
            }
        }

        DetailColorLabel.Text = Loc.GetString(Type == GenitalType.Breasts
            ? "genital-editor-nipple-color"
            : "genital-editor-detail-color");

        UpdateColorVisibility();
    }

    private void UpdateSkinToneVisibility()
    {
        var catalog = GetSelectedCatalog();
        var canSkinTone = catalog?.CanSkinTone ?? false;
        SkinToneCheck.Visible = canSkinTone;

        if (!canSkinTone)
            SkinToneCheck.Pressed = false;
    }

    private void UpdateVisibilityHelp()
    {
        var visibility = (GenitalVisibility) VisibilityButton.SelectedId;
        VisibilityHelpLabel.Text = Loc.GetString(VisibilityHelpLocaleKey(visibility));
    }

    private void UpdateSummary()
    {
        var catalog = GetSelectedCatalog();
        if (catalog == null || catalog.Sizes.Count == 0)
        {
            SummaryLabel.Text = string.Empty;
            return;
        }

        var sizeIndex = Math.Clamp(SizeButton.SelectedId, 0, catalog.Sizes.Count - 1);
        var visibility = (GenitalVisibility) VisibilityButton.SelectedId;
        SummaryLabel.Text = $"{Loc.GetString(catalog.Name)} · {Loc.GetString(catalog.Sizes[sizeIndex].Name)} · {Loc.GetString(VisibilityLocaleKey(visibility))}";
    }

    private void UpdateButtons()
    {
        RemoveButton.Disabled = !EnabledCheck.Pressed;
    }

    private GenitalOrganPrototype? GetSelectedCatalog()
    {
        if (_catalogs.Count == 0)
            return null;

        var index = Math.Clamp(TypeButton.SelectedId, 0, _catalogs.Count - 1);
        return _catalogs[index];
    }

    private static int ToPercent(float value)
    {
        return (int) MathF.Round(value * 100f);
    }

    private static string TypeLocaleKey(GenitalType type)
    {
        return $"genital-editor-{type.ToString().ToLowerInvariant()}";
    }

    private static string VisibilityLocaleKey(GenitalVisibility visibility)
    {
        return visibility switch
        {
            GenitalVisibility.AlwaysHidden => "genital-editor-visibility-always-hidden",
            GenitalVisibility.HiddenByUnderwear => "genital-editor-visibility-hidden-by-underwear",
            GenitalVisibility.HiddenByJumpsuit => "genital-editor-visibility-hidden-by-jumpsuit",
            GenitalVisibility.VisibleUnderClothes => "genital-editor-visibility-visible-under-clothes",
            GenitalVisibility.NeverHidden => "genital-editor-visibility-never-hidden",
            _ => "genital-editor-visibility-hidden-by-underwear",
        };
    }

    private static string VisibilityHelpLocaleKey(GenitalVisibility visibility)
    {
        return visibility switch
        {
            GenitalVisibility.AlwaysHidden => "genital-editor-visibility-help-always-hidden",
            GenitalVisibility.HiddenByUnderwear => "genital-editor-visibility-help-hidden-by-underwear",
            GenitalVisibility.HiddenByJumpsuit => "genital-editor-visibility-help-hidden-by-jumpsuit",
            GenitalVisibility.VisibleUnderClothes => "genital-editor-visibility-help-visible-under-clothes",
            GenitalVisibility.NeverHidden => "genital-editor-visibility-help-never-hidden",
            _ => "genital-editor-visibility-help-hidden-by-underwear",
        };
    }
}
