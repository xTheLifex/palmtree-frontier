using System.Linq;
using Content.Shared._PS.Interactions;
using Content.Shared._PS.Organs;
using Content.Shared.Preferences;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client._PS.Organs.UI;

/// <summary>
/// Palmtree: the Body tab. Height/width are always visible; the genital organ editor below is
/// hidden when the NSFW account gate is closed. Organ types are selected from a compact selector
/// and only the selected <see cref="GenitalOrganPanel"/> is visible.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class GenitalEditorControl : BoxContainer
{
    private static readonly GenitalType[] TypeOrder =
    {
        GenitalType.Penis,
        GenitalType.Vagina,
        GenitalType.Balls,
        GenitalType.Breasts,
        GenitalType.Butt,
        GenitalType.Belly,
    };

    private readonly IPrototypeManager _prototypes;
    private readonly Dictionary<GenitalType, List<GenitalOrganPrototype>> _catalogs = new();
    private readonly Dictionary<GenitalType, GenitalOrganPanel> _panels = new();
    private readonly Dictionary<GenitalType, Button> _selectorButtons = new();
    private readonly ButtonGroup _selectorGroup = new(false);

    private Color _skinColor = Color.White;
    private GenitalType? _selectedType;
    private bool _hasSettings;
    private bool _suppress;

    /// <summary>Raised when the user edits any organ or the global fluid setting.</summary>
    public event Action<GenitalOrganSettings>? SettingsChanged;

    /// <summary>Raised when the preview-only "Clothes" toggle changes.</summary>
    public event Action<bool>? ClothesToggled;

    /// <summary>Raised when the preview-only "Undergarments" toggle changes.</summary>
    public event Action<bool>? UndergarmentsToggled;

    /// <summary>Raised when the preview-only "Aroused" toggle changes.</summary>
    public event Action<bool>? ArousedToggled;

    /// <summary>Raised when the body height slider changes.</summary>
    public event Action<float>? HeightChanged;

    /// <summary>Raised when the body width slider changes.</summary>
    public event Action<float>? WidthChanged;

    /// <summary>The organ types that have a catalog and therefore a panel in this editor.</summary>
    public IEnumerable<GenitalType> OrganTypes => _panels.Keys;

    public GenitalEditorControl(IPrototypeManager prototypes)
    {
        _prototypes = prototypes;

        RobustXamlLoader.Load(this);

        BuildCatalogs();
        BuildPanels();

        foreach (var type in TypeOrder)
        {
            if (!_panels.ContainsKey(type))
                continue;

            SelectType(type);
            break;
        }

        FluidSpin.IsValid = value =>
            value >= GenitalOrganSettings.MinSemenVolume && value <= GenitalOrganSettings.MaxSemenVolume;
        FluidSpin.InitDefaultButtons();
        FluidSpin.OverrideValue(GenitalOrganSettings.DefaultSemenVolume);

        FluidSpin.ValueChanged += _ =>
        {
            if (_suppress)
                return;

            SettingsChanged?.Invoke(BuildSettings());
        };

        ClothesButton.OnToggled += args => ClothesToggled?.Invoke(args.Pressed);
        UndergarmentsButton.OnToggled += args => UndergarmentsToggled?.Invoke(args.Pressed);
        ArousedButton.OnToggled += args => ArousedToggled?.Invoke(args.Pressed);
        ResetAllButton.OnPressed += _ => ResetAll();

        HeightSlider.OnValueChanged += _ => OnHeightChanged();
        WidthSlider.OnValueChanged += _ => OnWidthChanged();
        HeightReset.OnPressed += _ =>
        {
            HeightSlider.SetValueWithoutEvent(1f);
            UpdateHeightLabel(1f);
            HeightChanged?.Invoke(1f);
        };
        WidthReset.OnPressed += _ =>
        {
            WidthSlider.SetValueWithoutEvent(1f);
            UpdateWidthLabel(1f);
            WidthChanged?.Invoke(1f);
        };

        SetBodySize(1f, 1f);
    }

    /// <summary>Applies the profile's body scale without raising the change events.</summary>
    public void SetBodySize(float height, float width)
    {
        height = Math.Clamp(height, HumanoidCharacterProfile.MinHeight, HumanoidCharacterProfile.MaxHeight);
        width = Math.Clamp(width, HumanoidCharacterProfile.MinWidth, HumanoidCharacterProfile.MaxWidth);

        var previousSuppress = _suppress;
        _suppress = true;
        HeightSlider.SetValueWithoutEvent(height);
        WidthSlider.SetValueWithoutEvent(width);
        UpdateHeightLabel(height);
        UpdateWidthLabel(width);
        _suppress = previousSuppress;
    }

    private void OnHeightChanged()
    {
        if (_suppress)
            return;

        var value = Math.Clamp(HeightSlider.Value, HumanoidCharacterProfile.MinHeight, HumanoidCharacterProfile.MaxHeight);
        HeightSlider.SetValueWithoutEvent(value);
        UpdateHeightLabel(value);
        HeightChanged?.Invoke(value);
    }

    private void OnWidthChanged()
    {
        if (_suppress)
            return;

        var value = Math.Clamp(WidthSlider.Value, HumanoidCharacterProfile.MinWidth, HumanoidCharacterProfile.MaxWidth);
        WidthSlider.SetValueWithoutEvent(value);
        UpdateWidthLabel(value);
        WidthChanged?.Invoke(value);
    }

    private void UpdateHeightLabel(float value)
    {
        HeightLabel.Text = Loc.GetString("humanoid-profile-editor-height-label",
            ("height", $"{value * 100f:F0}%"));
    }

    private void UpdateWidthLabel(float value)
    {
        WidthLabel.Text = Loc.GetString("humanoid-profile-editor-width-label",
            ("width", $"{value * 100f:F0}%"));
    }

    /// <summary>
    /// Applies the profile's organ settings without raising <see cref="SettingsChanged"/>.
    /// </summary>
    public void SetSettings(GenitalOrganSettings settings, Color skinColor)
    {
        _skinColor = skinColor;

        _suppress = true;
        FluidSpin.OverrideValue(Math.Clamp(settings.SemenVolume,
            GenitalOrganSettings.MinSemenVolume,
            GenitalOrganSettings.MaxSemenVolume));
        _suppress = false;

        foreach (var (type, panel) in _panels)
        {
            panel.SetData(settings.Get(type), skinColor);
            UpdateSelectorState(type);
        }

        if (!_hasSettings || _selectedType == null || !_panels.ContainsKey(_selectedType.Value))
        {
            GenitalType? selected = null;

            foreach (var type in TypeOrder)
            {
                if (_panels.TryGetValue(type, out var panel) && panel.Enabled)
                {
                    selected = type;
                    break;
                }
            }

            if (selected == null)
            {
                foreach (var type in TypeOrder)
                {
                    if (_panels.ContainsKey(type))
                    {
                        selected = type;
                        break;
                    }
                }
            }

            if (selected is { } first)
                SelectType(first);
        }
        else
        {
            SelectType(_selectedType.Value);
        }

        _hasSettings = true;
    }

    /// <summary>Applies the preview toggles without raising their events.</summary>
    public void SetPreviewState(bool clothes, bool undergarments, bool aroused)
    {
        ClothesButton.Pressed = clothes;
        UndergarmentsButton.Pressed = undergarments;
        ArousedButton.Pressed = aroused;
    }

    /// <summary>
    /// Palmtree: keeps the body-size controls visible when the NSFW age gate is closed while hiding
    /// the genital organ editor.
    /// </summary>
    public void SetGenitalContentVisible(bool visible)
    {
        GenitalContent.Visible = visible;
    }

    private void BuildCatalogs()
    {
        foreach (var catalog in _prototypes.EnumeratePrototypes<GenitalOrganPrototype>())
        {
            if (!_catalogs.TryGetValue(catalog.GenitalType, out var list))
                _catalogs[catalog.GenitalType] = list = new List<GenitalOrganPrototype>();

            list.Add(catalog);
        }

        foreach (var list in _catalogs.Values)
        {
            list.Sort((a, b) => string.Compare(
                Loc.GetString(a.Name),
                Loc.GetString(b.Name),
                StringComparison.CurrentCultureIgnoreCase));
        }
    }

    private void BuildPanels()
    {
        foreach (var type in TypeOrder)
        {
            if (!_catalogs.TryGetValue(type, out var catalogs) || catalogs.Count == 0)
                continue;

            var button = new Button
            {
                Text = Loc.GetString(TypeLocaleKey(type)),
                ToggleMode = true,
                Group = _selectorGroup,
                HorizontalExpand = true,
                MinWidth = 90,
                MinHeight = 30,
            };
            button.OnPressed += _ => SelectType(type);
            OrganSelector.AddChild(button);
            _selectorButtons[type] = button;

            var panel = new GenitalOrganPanel(type, catalogs, _prototypes);
            panel.Changed += () => OnPanelChanged(type);
            panel.Visible = false;
            PanelHost.AddChild(panel);
            _panels[type] = panel;
        }
    }

    private void SelectType(GenitalType type)
    {
        if (!_panels.TryGetValue(type, out var selectedPanel))
            return;

        _selectedType = type;

        foreach (var (panelType, panel) in _panels)
        {
            panel.Visible = panelType == type;
        }

        if (_selectorButtons.TryGetValue(type, out var button))
            button.Pressed = true;

        selectedPanel.Visible = true;
    }

    private void OnPanelChanged(GenitalType type)
    {
        UpdateSelectorState(type);

        if (_suppress)
            return;

        SettingsChanged?.Invoke(BuildSettings());
    }

    private GenitalOrganSettings BuildSettings()
    {
        var settings = new GenitalOrganSettings
        {
            SemenVolume = Math.Clamp(FluidSpin.Value,
                GenitalOrganSettings.MinSemenVolume,
                GenitalOrganSettings.MaxSemenVolume),
        };

        foreach (var (type, panel) in _panels)
        {
            if (panel.BuildData() is { } data)
                settings.Set(type, data);
        }

        return settings;
    }

    private void UpdateSelectorState(GenitalType type)
    {
        if (!_selectorButtons.TryGetValue(type, out var button) ||
            !_panels.TryGetValue(type, out var panel))
        {
            return;
        }

        var name = Loc.GetString(TypeLocaleKey(type));
        button.Text = panel.Enabled ? $"● {name}" : $"○ {name}";
        button.ToolTip = panel.Enabled ? panel.Summary : Loc.GetString("genital-editor-not-set");
    }

    private void ResetAll()
    {
        SetSettings(new GenitalOrganSettings(), _skinColor);
        SettingsChanged?.Invoke(BuildSettings());
    }

    private static string TypeLocaleKey(GenitalType type)
    {
        return $"genital-editor-{type.ToString().ToLowerInvariant()}";
    }
}
